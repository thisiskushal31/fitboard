def _hit(blob: str, needle: str) -> bool:
    needle = needle.lower()
    if len(needle.strip()) <= 3 or needle.startswith(" ") or needle.endswith(" "):
        return re.search(rf"(?<![a-z0-9]){re.escape(needle.strip())}(?![a-z0-9])", blob) is not None
    return needle in blob


def detect_regions(text: str, remote: bool | None = None) -> list[str]:
    """Tag a listing with canonical regions. UK/DE/Nordics also imply EMEA; SG/IN imply APAC."""
    blob = (text or "").lower()
    found: list[str] = []
    if remote or _hit(blob, "remote") or _hit(blob, "worldwide"):
        found.append("Remote")
    for name in REGION_ORDER:
        if name == "Remote":
            continue
        if any(_hit(blob, hint) for hint in REGION_HINTS[name]):
            found.append(name)
    if "UK" in found and "EMEA" not in found:
        found.append("EMEA")
    if "Germany" in found and "EMEA" not in found:
        found.append("EMEA")
    if "Nordics" in found and "EMEA" not in found:
        found.append("EMEA")
    if "Middle East" in found and "EMEA" not in found:
        found.append("EMEA")
    if "Singapore" in found and "APAC" not in found:
        found.append("APAC")
    if "India" in found and "APAC" not in found:
        found.append("APAC")
    return found


def location_score(text: str, remote: bool | None, profile: Profile) -> tuple[float, list[str]]:
    """Highest LOCATION_WEIGHT among detected regions. Remote is always 1.0."""
    regions = detect_regions(text, remote)
    if "Remote" in regions:
        return 1.0, regions
    if not regions:
        if "hybrid" in (text or "").lower():
            return 0.7, ["Hybrid"]
        return 0.55, []
    score = max(LOCATION_WEIGHTS.get(r, 0.5) for r in regions)
    if "hybrid" in (text or "").lower():
        score = max(score, 0.7)
    return round(score, 2), regions
